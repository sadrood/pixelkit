export const DICTS: Record<Lang, Dict> = { zh, en };

/** 取值并做 {占位符} 替换 */
export function t(lang: Lang, key: keyof Dict, vars?: Record<string, string | number>): string {
  let s: string = DICTS[lang][key] ?? DICTS.en[key] ?? String(key);
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}

/** 检测初始语言：?lang= > localStorage roamdial.lang > navigator.language */
export function detectLang(): Lang {
  try {
    const q = new URLSearchParams(location.search).get("lang");
    if (q === "zh" || q === "en") return q;
    const saved = localStorage.getItem("roamdial.lang");
    if (saved === "zh" || saved === "en") return saved;
  } catch {
    /* ignore */
  }
  return /^zh/i.test(navigator.language || "") ? "zh" : "en";
}
